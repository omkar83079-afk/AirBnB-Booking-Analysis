# 2. Build PDF Document
pdf_path = 'Airbnb_Data_Analysis_Report.pdf'
doc = SimpleDocTemplate(pdf_path, pagesize=letter, rightMargin=54, leftMargin=54, topMargin=54, bottomMargin=54)
story = []

# Styles
styles = getSampleStyleSheet()
title_style = ParagraphStyle(
    'ReportTitle',
    parent=styles['Heading1'],
    fontSize=22,
    textColor=colors.HexColor('#FF5A5F'),
    spaceAfter=15,
    alignment=1
)
heading_style = ParagraphStyle(
    'Heading',
    parent=styles['Heading2'],
    fontSize=14,
    textColor=colors.HexColor('#484848'),
    spaceBefore=12,
    spaceAfter=6
)
body_style = ParagraphStyle(
    'Body',
    parent=styles['Normal'],
    fontSize=10,
    leading=14,
    textColor=colors.HexColor('#484848'),
    spaceAfter=10
)

# Title Page / Header
story.append(Paragraph("Airbnb NYC Open Data Analysis Report", title_style))
story.append(Paragraph("An automated summary of exploratory data analysis, data quality checks, and cleaning transformations.", body_style))
story.append(Spacer(1, 15))

# Executive Summary
story.append(Paragraph("1. Executive Summary", heading_style))
summary_text = f"The dataset contains details of Airbnb listings in New York City with {df.shape[0]:,} unique records and {df.shape[1]} features after removing duplicates. Exploratory plots suggest pricing values in the source dataset are uniformly distributed, implying simulated parameters. Essential cleaning steps were performed to handle invalid dates, missing descriptions, and column structural transformations."
story.append(Paragraph(summary_text, body_style))
story.append(Spacer(1, 10))

# Data Cleaning Metrics
story.append(Paragraph("2. Data Integrity & Cleaning Actions", heading_style))
cleaning_text = ("<ul>"
                 "<li><b>Duplicates</b>: Removed redundant rows to preserve unique structural entries.</li>"
                 "<li><b>Missing Identifiers</b>: Excluded rows lacking critical descriptors (NAME and Host Name).</li>"
                 "<li><b>Financial Fields</b>: Stripped character symbols ($) and cast price columns into active numerical floats.</li>"
                 "<li><b>Date Imputations</b>: Transformed review timelines, addressing extreme out-of-bounds dates spanning up to 2058.</li>"
                 "</ul>")
story.append(Paragraph(cleaning_text, body_style))
story.append(Spacer(1, 10))

# Visualizations Section
story.append(Paragraph("3. Exploratory Data Visualizations", heading_style))
story.append(Paragraph("Below are the analytical visualizations revealing the distributions of prices, room choices, and regions:", body_style))

# Embed Plots
story.append(Image('price_dist.png', width=5.5*inch, height=2.75*inch))
story.append(Spacer(1, 10))
story.append(Image('room_type_dist.png', width=5.5*inch, height=2.75*inch))
story.append(Spacer(1, 10))
story.append(Image('neighborhood_dist.png', width=5.5*inch, height=2.75*inch))

# Build Document
doc.build(story)

# Download to client browser
